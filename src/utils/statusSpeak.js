/* "งานครูแอนเสร็จแล้ว" — เปลี่ยนสถานะงานด้วยประโยคที่พูดจริง (V2 §3)
 *
 * ร้านไม่ได้จำเลขงาน ร้านจำว่า "งานของใคร" — ประโยคจึงเป็น ชื่อ + คำบอกสถานะ
 * ม่วงไปหางานที่ตรงกันให้ เจอใบเดียวทำเลย เจอหลายใบให้เลือกก่อน (ห้ามเดา
 * เรื่องที่มีผลกับยอดบัญชี)
 *
 * กันพลาดสองชั้น:
 *   - ประโยคต้องไม่มีตัวเลข — มีตัวเลขคือการจดงานใหม่ ("กรอบรูป 2 อัน จ่ายแล้ว")
 *   - ต้องมีชื่อนำหน้าอย่างน้อย 2 ตัวอักษร — "เสร็จแล้ว" โดด ๆ กำกวมเกินไป
 */

const ENDINGS = [
  // [regex ท้ายประโยค, การเปลี่ยนแปลงแบบเดียวกับปุ่มบนแผงสถานะ, ป้ายที่ตอบกลับ]
  [/(?:ทำ)?เสร็จ(?:แล้ว|ละ|เรียบร้อย(?:แล้ว)?)$/u, { done: true }, '✓ ทำเสร็จแล้ว'],
  [/(?:ลูกค้า)?(?:มา)?รับ(?:ของ|งาน)?(?:ไป)?แล้ว$/u, { picked: true }, '📦 ลูกค้ารับของแล้ว'],
  [/จ่าย(?:เงิน)?สด(?:แล้ว)?$/u, { money: 'cash' }, '💵 รับเงินสดแล้ว'],
  [/โอน(?:เงิน)?(?:มา)?แล้ว$/u, { money: 'transfer' }, '🏦 รับเงินโอนแล้ว'],
  [/ลงบัญชี(?:ไว้|แล้ว)$/u, { money: 'account' }, '📒 ลงบัญชีไว้แล้ว (ยังไม่ได้รับเงิน)'],
  // จ่ายแล้วแต่ไม่บอกทาง — ได้เงินจริง แต่สด/โอนต้องถาม ไม่เดา
  [/(?:จ่าย|ชำระ|ได้|เก็บ)เงิน(?:ครบ|เต็ม)?แล้ว$/u, { ask: 'method' }, '💰 ได้รับเงินแล้ว'],
  [/จ่าย(?:ครบ)?แล้ว$/u, { ask: 'method' }, '💰 ได้รับเงินแล้ว'],
];

// → { name, change|null, ask|null, label } หรือ null เมื่อไม่ใช่ประโยคบอกสถานะ
export function parseStatusSpeak(text) {
  const raw = String(text ?? '').trim().replace(/\s+/g, ' ');
  if (!raw || raw.includes('\n') || /[\d๐-๙]/.test(raw)) return null;

  for (const [re, change, label] of ENDINGS) {
    const m = re.exec(raw);
    if (!m || m.index === 0) continue; // ไม่มีชื่อนำหน้า = กำกวม ไม่ทำ
    let name = raw.slice(0, m.index).trim();
    // "งานครูแอน" → ครูแอน · "ของครูแอน" → ครูแอน
    name = name.replace(/^(?:งาน|ของ|อัน|ใบ)\s*/u, '').replace(/\s*(?:งาน)?$/u, '').trim();
    if (name.length < 2 || name.length > 40) return null;
    return { name, change: change.ask ? null : change, ask: change.ask || null, label };
  }
  return null;
}
