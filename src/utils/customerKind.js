import { isOrgCustomer } from './nlParser.js';

/* ลูกค้าสองแบบ ที่ร้านทำงานกับมันคนละอย่างกันจริง ๆ
 *
 * ร้านบอกว่า "แยกงานโรงเรียนกับงานทั่วไปให้หน่อย ฟีลแบบ เก็บเงินสดหน้าร้านแล้ว
 * แล้วก็ลงบัญชี" — สองประโยคนี้บอกทั้งการแบ่งและเหตุผลของการแบ่ง
 *
 *   🏫 หน่วยงาน  โรงเรียน · ธกส · อบต · วัด — สั่งแล้วเอาของไปก่อน วางบิลไว้
 *                ต้องรู้ว่าใคร นัดรับวันไหน และต้องออกใบเสร็จให้เอาไปลงบัญชี
 *                งานพวกนี้คือ "ค้างรับ" ที่ต้องตามเก็บเงิน
 *
 *   🏪 หน้าร้าน   ลูกค้าเดินเข้ามา จ่ายสด รับของกลับ จบ
 *                ไม่ต้องรู้ชื่อ ไม่ต้องนัดวัน ไม่ต้องตามเก็บ — แค่ลงบัญชีว่า
 *                วันนี้ขายอะไรไปเท่าไหร่
 *
 * เดาจากชื่อลูกค้า ไม่ได้เก็บเป็นช่องใหม่ในฐานข้อมูล เพราะมันคิดจากสิ่งที่มี
 * อยู่แล้วได้ และเดาผิดก็กดสลับได้ในหน้าแก้ไข — เก็บซ้ำเมื่อไหร่ก็มีวันที่ชื่อ
 * ลูกค้ากับประเภทขัดกันเอง
 */

export const JOB_KINDS = [
  { id: 'org', icon: '🏫', label: 'หน่วยงาน', short: 'หน่วยงาน', hint: 'วางบิล · ออกใบเสร็จ' },
  { id: 'walkin', icon: '🏪', label: 'หน้าร้าน', short: 'หน้าร้าน', hint: 'เก็บเงินสดแล้ว' },
];

/* งานใบนี้เป็นของใคร — คืน 'org' หรือ 'walkin'
 *
 * รับได้ทั้งตัวงานและชื่อลูกค้าเปล่า ๆ เพราะหน้าเว็บมีทั้งสองแบบในมือ
 */
export function customerKind(job) {
  const name = typeof job === 'string' ? job : job?.customer_name;
  return isOrgCustomer(name) ? 'org' : 'walkin';
}

export function kindMeta(id) {
  return JOB_KINDS.find((k) => k.id === id) || JOB_KINDS[1];
}
