// สิ่งที่ม่วงพิมพ์มาเองตอนร้านหายไปหลายวัน
//
// ร้านขอมาว่า "อยากให้ม่วงเป็นกันเอง ถ้าเราหายไปสักพัก อยากให้นางทักมา" พร้อม
// ตัวอย่างสองอัน: "ฟิล์มมีงานให้จดมั้ย" กับ "ฟิล์มจดงานได้แล้ว แม่บ่นไม่รู้
// ด้วยนะ" — เรียกชื่อ สั้น ๆ หยอกได้ ไม่ใช่เสียงแอปเตือน
//
// เขียนไว้เป็นชุดแล้วสลับกัน เพราะประโยคเดิมทุกครั้งอ่านครั้งที่สามก็รู้ว่า
// เครื่องพิมพ์ ไม่ใช่คนทัก
//
// เรียงตาม "ทักครั้งที่เท่าไหร่แล้ว": ครั้งแรกถามเฉย ๆ ครั้งหลัง ๆ หยอกขึ้น
// เพราะหายไปนานขึ้น แล้วก็หยุด
const LINES = [
  [
    '{name} มีงานให้จดมั้ยคะ 💜',
    '{name}ขา หายไปเลย มีงานให้ม่วงจดมั้ยคะ',
    'ม่วงว่าง ๆ อยู่ค่ะ {name} มีอะไรให้จดมั้ยคะ 🐶',
  ],
  [
    '{name} จดงานได้แล้วนะคะ เดี๋ยวแม่บ่นม่วงไม่รู้ด้วยนะ 😆',
    '{name}~ สมุดเริ่มฝุ่นจับแล้วค่ะ 🧹 มีงานเข้ามั้ยคะ',
    'ม่วงรอจนหลับไปแล้วรอบนึง 😴 {name} มีงานให้จดยัง',
  ],
  [
    '{name} ไม่จดก็ไม่รู้นะคะว่าเดือนนี้ได้เท่าไหร่ 👀 มีงานมั้ยคะ',
    'ม่วงทักครั้งสุดท้ายแล้วนะคะ {name} 💜 ถ้ามีงานเมื่อไหร่ ม่วงอยู่ตรงนี้ตลอดค่ะ',
  ],
];

// ชื่อที่จะเรียก: ชื่อจริงถ้ารู้ ไม่รู้ก็ไม่ต้องเรียกชื่อ ดีกว่าเรียกผิด
//
// LINE display name ยาวได้มาก และบางคนตั้งเป็นประโยคทั้งท่อน เอามาแค่คำแรก
// พอ — "คุณ" ที่ต่อหน้าชื่อเล่นฟังดูห่าง จึงเรียกชื่อเปล่า ๆ แบบที่ร้านเขียน
// ตัวอย่างมาเอง
export function callName(displayName) {
  const first = String(displayName || '').trim().split(/\s+/)[0] || '';
  return first.length > 0 && first.length <= 20 ? first : '';
}

// ข้อความสำหรับการทักครั้งที่ `streak` (เริ่มที่ 0) ของร้านนี้
//
// `pick` มีไว้ให้เทสต์เลือกได้แน่นอน ของจริงสุ่ม — ร้านเดียวกันจะได้ไม่เจอ
// ประโยคเดิมสองรอบติด
export function nudgeText(displayName, streak = 0, pick = Math.random) {
  const tier = LINES[Math.min(Math.max(streak, 0), LINES.length - 1)];
  const line = tier[Math.floor(pick() * tier.length) % tier.length];
  const name = callName(displayName);
  // ไม่มีชื่อก็ต้องไม่เหลือช่องว่างหรือ "ขา" ลอย ๆ ไว้กลางประโยค
  return name
    ? line.replace(/\{name\}/g, name)
    : line.replace(/\{name\}(?:ขา|~|ขา)?\s*/g, '').replace(/^\s+/, '').replace(/\s{2,}/g, ' ');
}

// ตัวอย่างทั้งชุดในข้อความเดียว ตอบคำสั่ง "ทดสอบทัก"
//
// ของแบบนี้ถ้าดูไม่ได้จนกว่าจะหายไปจริงสามวัน ก็แก้คำพูดไม่ได้จนกว่าจะถึงตอนนั้น
// เหมือนกัน และสิ่งที่ร้านอยากรู้คือ "น้ำเสียงใช่มั้ย" ซึ่งดูจากประโยคเดียว
// ไม่ออก
export function nudgePreview(displayName, pick = Math.random) {
  const lines = [];
  for (let tier = 0; tier < MAX_NUDGES; tier += 1) {
    lines.push(`${tier + 1}. ${nudgeText(displayName, tier, pick)}`);
  }
  return (
    `นี่คือที่ม่วงจะทักค่ะ ถ้า${callName(displayName) || 'คุณ'}หายไปหลายวัน 💜\n\n` +
    `${lines.join('\n\n')}\n\n` +
    'ของจริงจะมาทีละอัน ห่างกันหลายวัน และสลับประโยคไปเรื่อย ๆ นะคะ\n' +
    'ไม่ชอบแบบไหนบอกได้เลยค่ะ'
  );
}

// ทักไปกี่ครั้งแล้วถึงพอ — เท่ากับจำนวนชั้นของประโยคข้างบน ชั้นสุดท้ายบอกเอง
// ว่าเป็นครั้งสุดท้าย จึงต้องไม่มีครั้งที่ถัดจากนั้น
export const MAX_NUDGES = LINES.length;
