import { test } from 'node:test';
import assert from 'node:assert/strict';
import { splitDump, groupLines } from '../src/utils/dumpSplit.js';
import { parseNaturalJob, extractCustomer, statedLineTotal } from '../src/utils/nlParser.js';
import { matchSqmRate } from '../src/utils/area.js';

/* ร้านพิมพ์ใบสั่งทั้งใบมาในข้อความเดียว แล้วม่วงไม่เข้าใจ
 *
 * ร้านส่งรูปหน้าจอมาพร้อมคำว่า "พอพิมพ์ไปก็ไม่เข้าใจอ่ะ" — ม่วงตอบกลับไปว่า
 * "ต้องการเจาะตาไก่ไหมคะ?" แล้ว "ราคาป้ายละเท่าไหร่คะ?" ทั้งที่ร้านพิมพ์ราคา
 * มาครบทุกบรรทัดแล้ว
 *
 * ของเดิมอ่านได้ ฿4,038 จากใบที่ร้านคิดเองได้ ฿8,276 — ขาดไปครึ่งใบ แล้วยัง
 * แตกเป็นสี่งานที่มีลูกค้าปลอมสี่คน (ครูยิ้ม, ครูออฟ) ส่วนโรงเรียนที่ร้านตั้งใจ
 * เขียนไว้บรรทัดแรกหายไปเลย ออกใบเสร็จให้ใครไม่ได้สักใบ
 */
const ORDER = `รร สบกอน
โฟมบอร์ด
รูปครูยิ้ม 1*1.5*700*2=2,100
รูปครูออฟ 1*1.5*700*2=2,100
ป้ายเกษียณ 1.2*1.7*600*2=2,448
สแตนดี้ สูง
0.6*1.7*700*2=1,428+200=1,628`;

test('ใบสั่งทั้งใบของโรงเรียนเดียว = งานเดียว ยอดตรงกับที่ร้านคิดเอง', () => {
  const { jobs, total } = splitDump(ORDER);

  assert.equal(jobs.length, 1, 'ใบเดียวถูกแตกเป็นหลายงาน ออกใบเสร็จไม่ได้');
  assert.equal(total, 8276, 'คิดเงินขาด — ร้านบวกเองได้ 2100+2100+2448+1628');

  const [job] = jobs;
  assert.equal(job.customerName, 'รรสบกอน', 'โรงเรียนที่ร้านเขียนไว้หัวใบหายไป');
  assert.equal(job.jobName, 'โฟมบอร์ด', 'วัสดุที่เขียนไว้บรรทัดเดียวข้างบนหายไป');
  assert.equal(job.items.length, 4);
});

/* ชื่อชิ้นงานต้องอยู่ครบ ไม่งั้นใบเสร็จมีของชื่อซ้ำกันสองบรรทัด
 *
 * "รูปครูยิ้ม" คือรูปของครูยิ้ม ไม่ใช่ลูกค้าชื่อครูยิ้ม — ถ้าชื่อถูกยกออกไป
 * เป็นลูกค้า ของจะเหลือชื่อ "รูป" สองรายการเหมือนกันเป๊ะ ร้านแยกไม่ออกว่า
 * อันไหนของใคร
 */
test('ชื่อคนที่อยู่กลางบรรทัด เป็นชื่อชิ้นงาน ไม่ใช่ลูกค้าคนใหม่', () => {
  const [job] = splitDump(ORDER).jobs;

  assert.deepEqual(
    job.items.map((it) => it.item_name),
    ['รูปครูยิ้ม', 'รูปครูออฟ', 'ป้ายเกษียณ', 'สแตนดี้']
  );
});

test('ตัวคูณที่สี่คือจำนวนชิ้น ไม่ใช่ส่วนหนึ่งของราคา', () => {
  const [job] = splitDump(ORDER).jobs;

  for (const it of job.items) {
    assert.equal(it.quantity, 2, `${it.item_name} ควรเป็นสองชิ้น`);
  }

  // 1 × 1.5 = 1.5 ตร.ม. × 700 = 1,050 ต่อชิ้น × 2 = 2,100
  assert.equal(job.items[0].unit_price, 1050);
  assert.equal(job.items[0].total, 2100);

  // ของเดิม matchSqmRate อ่านแค่สามตัว ตัวที่สี่หล่นหาย
  assert.equal(matchSqmRate('1*1.5*700*2').pieces, 2);
  assert.equal(matchSqmRate('1*1.5*700*2').rate, 700);
  // ไม่มีตัวที่สี่ = ร้านไม่ได้บอกจำนวนในสูตร ปล่อยให้คำอย่าง "2 แผ่น" ตอบแทน
  assert.equal(matchSqmRate('1*1.5*700').pieces, null);
  assert.equal(matchSqmRate('1*1.5*700*2 จำนวน 5 แผ่น').pieces, 2, 'สูตรที่ร้านเขียนเองต้องชนะ');
});

/* ร้านพิมพ์คำตอบมาแล้ว อย่าไปคิดใหม่ให้ต่างจากที่เขาบอกลูกค้า
 *
 * บรรทัดขาตั้งมีค่าขาตั้งบวกเพิ่ม: 1,428+200=1,628 ถ้าคิดเองจากขนาดจะได้
 * 1,428 แล้วค่าขาตั้ง 200 หายไปเงียบ ๆ
 */
test('ยอดที่ร้านเขียนหลังเท่ากับ ชนะยอดที่ม่วงคิดเอง', () => {
  const [job] = splitDump(ORDER).jobs;
  const standee = job.items[3];

  assert.equal(standee.total, 1628, 'ค่าขาตั้ง 200 ที่ร้านบวกเพิ่มหายไป');
  assert.equal(standee.unit_price, 814, 'ราคาต่อชิ้นต้องหารจากยอดที่ร้านเขียน');

  assert.equal(statedLineTotal('0.6*1.7*700*2=1,428+200=1,628'), 1628);
  assert.equal(statedLineTotal('1*1.5*700*2=2,100'), 2100);
  assert.equal(statedLineTotal('โฟมบอร์ด 100*150*600'), null, 'ไม่มีเท่ากับ = ไม่ได้บอกยอด');
});

/* "รร" เป็นคำนำหน้าชื่อโรงเรียน แต่ก็เป็นตัวอักษรกลางคำไทยอีกหลายคำ
 *
 * ภาษาไทยไม่เว้นวรรค การจับ "รร" แบบไม่ดูตัวหน้าจะได้ลูกค้าชื่อ "รรมชาติ"
 * จาก "ธรรมชาติ" แล้วออกใบเสร็จผิดคน
 */
test('"รร" นำหน้าชื่อโรงเรียนได้ แต่ห้ามจับกลางคำ', () => {
  assert.equal(extractCustomer('รร สบกอน').customerName, 'รรสบกอน');
  assert.equal(extractCustomer('รร.บ้านปงสนุก').customerName, 'รร.บ้านปงสนุก');

  for (const word of ['ป้ายธรรมชาติ', 'บรรทัด 10 อัน', 'กรรไกร 2 อัน', 'ป้ายธรรมะ']) {
    assert.equal(extractCustomer(word).customerName, null, `${word} ไม่ใช่ชื่อลูกค้า`);
  }
});

/* เส้นแบ่งระหว่าง "ลูกค้าคนใหม่" กับ "ชื่อชิ้นงาน" คือตำแหน่งในบรรทัด
 *
 * คนจดขึ้นต้นบรรทัดด้วยชื่อลูกค้าเสมอเวลาเปลี่ยนคน ถ้าชื่ออยู่กลางบรรทัดแปลว่า
 * มันเป็นส่วนหนึ่งของของที่สั่ง
 */
test('ชื่อลูกค้าที่อยู่หน้าบรรทัด ปิดกลุ่มของคนก่อนหน้า', () => {
  const groups = groupLines(`พี่ต่าย
สติ๊กเกอร์ 50 ดวง ดวงละ 5
รูปครูยิ้ม 1*1.5*700*2=2,100
ครูแดง ตรายาง 1 อัน 250`);

  assert.equal(groups.length, 2);
  assert.equal(groups[0].customer, 'พี่ต่าย');
  assert.equal(groups[0].lines.length, 2, 'ชื่อกลางบรรทัดไม่ควรตัดกลุ่ม');
  assert.equal(groups[1].customer, null, 'บรรทัดที่มีชื่อของตัวเองอ่านชื่อจากบรรทัด');
  assert.deepEqual(groups[1].lines, ['ครูแดง ตรายาง 1 อัน 250']);
});

/* ลูกค้าคนเดียวพิมพ์มาบรรทัดเดียว ยังต้องเหมือนเดิม
 *
 * ทางนี้เป็นทางที่ใช้บ่อยที่สุด การแก้เรื่องกองหลายบรรทัดต้องไม่ไปแตะมัน
 */
test('บรรทัดเดียวยังอ่านชื่อลูกค้าจากในบรรทัดเหมือนเดิม', () => {
  const d = parseNaturalJob('งานโฟมบอร์ด รร สบกอน คนสั่งน้องทีน ขนาด 100*150*600');
  assert.equal(d.customerName, 'น้องทีน');
  assert.equal(d.total, 900);
});
