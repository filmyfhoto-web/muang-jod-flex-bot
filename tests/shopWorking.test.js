import { test } from 'node:test';
import assert from 'node:assert/strict';
import { splitDump, groupLines } from '../src/utils/dumpSplit.js';
import { parseNaturalJob, extractGrandTotal, stripEmphasis } from '../src/utils/nlParser.js';

/* ร้านเขียนวิธีคิดที่ต้องการมาให้ทีละขั้น แล้วบอกว่า "มันต้องคิดแบบนี้"
 *
 * รูปแบบที่ร้านใช้คือ "สูตร = ราคาต่อชิ้น   ต่อชิ้น × จำนวน = ยอด" และคร่อม
 * ตัวเลขสำคัญด้วยดาวเพื่อเน้น ซึ่งชนกับดาวที่เป็นเครื่องหมายคูณของเราพอดี
 *
 * ของเดิมอ่านกองนี้ได้ ฿17,024 จากใบที่ร้านคิดเองได้ ฿8,800 — เกินมาเกือบเท่าตัว
 * เพราะบรรทัดสรุปท้ายกองถูกนับเป็นรายการที่ห้าราคา ฿8,800
 */
const WORKED = `โฟมบอร์ด รร สบกอน
รูปครูยิ้ม 1*1.5*700 = *1,050*  2 อัน 1050*2 = *2,100*
รูปครูออฟ 1*1.5*700 = *1,050* 2 อัน 1050*2 = *2,100*
ป้ายเกษียณ 1.2*1.7*600 = 900   900*2=*1800*
สแตนดี้ สูง 0.6*1.7  ชุดละ 1400   1400*2=2800

ทั้งหมด 2100+2100+1800+2800 = *8,800*.   มันต้องคิดแบบนี้`;

test('ร้านเขียนวิธีคิดมาเอง ม่วงได้ยอดเดียวกับร้าน', () => {
  const { jobs, total } = splitDump(WORKED);

  assert.equal(jobs.length, 1);
  assert.equal(total, 8800, 'คิดเกิน — บรรทัดสรุปถูกนับเป็นรายการ');

  const [job] = jobs;
  assert.equal(job.customerName, 'รรสบกอน');
  assert.equal(job.items.length, 4, 'บรรทัดสรุปกลายเป็นรายการที่ห้า');
  assert.deepEqual(
    job.items.map((it) => [it.quantity, it.unit_price, it.total]),
    [[2, 1050, 2100], [2, 1050, 2100], [2, 900, 1800], [2, 1400, 2800]]
  );
});

/* หัวกลุ่มบอกทั้งวัสดุและลูกค้าในบรรทัดเดียว
 *
 * ร้านเขียนสองแบบสลับกัน คราวก่อนแยกสองบรรทัด คราวนี้รวมเป็น "โฟมบอร์ด รร สบกอน"
 */
test('วัสดุกับชื่อลูกค้าอยู่บรรทัดเดียวกันได้', () => {
  const [job] = splitDump(WORKED).jobs;
  assert.equal(job.jobName, 'โฟมบอร์ด', 'วัสดุที่ร้านพิมพ์เองหายไป');
  assert.equal(job.customerName, 'รรสบกอน');

  // แยกสองบรรทัดก็ยังได้เหมือนเดิม
  const [split] = splitDump('รร สบกอน\nโฟมบอร์ด\nป้าย 1*1.5*700*2=2,100').jobs;
  assert.equal(split.jobName, 'โฟมบอร์ด');
  assert.equal(split.customerName, 'รรสบกอน');
});

/* ดาวคร่อมตัวเลขคือการเน้น ไม่ใช่ตัวคูณ
 *
 * ยอดที่ร้านเขียนไว้ท้ายบรรทัดอ่านไม่ออกเพราะมีดาวปิดท้าย ม่วงเลยไปคิดเลขเอง
 */
test('ดาวคร่อมตัวเลขไม่ใช่เครื่องหมายคูณ', () => {
  assert.equal(stripEmphasis('900*2=*1800*'), '900*2=1800');
  assert.equal(stripEmphasis('= *1,050*  2 อัน'), '= 1,050  2 อัน');

  // ตัวคูณจริงต้องไม่โดนแตะ
  assert.equal(stripEmphasis('1*1.5*700*2'), '1*1.5*700*2');
  assert.equal(stripEmphasis('0.6*1.7'), '0.6*1.7');

  // ดาวข้างเดียวไม่ใช่คู่ ไม่ต้องเดา
  assert.equal(stripEmphasis('รวม *300'), 'รวม *300');
});

/* บรรทัดสรุปที่ร้านพิมพ์คำพูดต่อท้าย
 *
 * ของเดิมบรรทัดสรุปต้องจบที่ตัวเลขพอดีถึงจะรับ พอร้านคุยต่อในบรรทัดเดียวกัน
 * มันเลยกลายเป็นรายการราคา ฿8,800 บวกยอดทั้งกองซ้ำอีกรอบ
 */
test('ยอดรวมที่มีคำพูดต่อท้าย ยังเป็นยอดรวม', () => {
  assert.equal(extractGrandTotal('ทั้งหมด 2100+2100 = 4,200.   มันต้องคิดแบบนี้').total, 4200);
  assert.equal(extractGrandTotal('รวม 6*50 = *300* นะคะ').total, 300);

  // จุดปิดประโยคไม่ใช่จุดทศนิยม — เคยอ่าน "8,800." ได้ 8
  assert.equal(extractGrandTotal('ทั้งหมด 1+2 = 8,800. จบ').total, 8800);
  assert.equal(extractGrandTotal('ทั้งหมด 1+2 = 8,800.50 บาท').total, 8800.5);

  /* ไม่มีเครื่องหมายเท่ากับ = ยังเป็นของที่สั่ง ไม่ใช่ยอดรวม
   *
   * เส้นแบ่งนี้คือทั้งหมดที่กันไม่ให้ "ทั้งหมด 2 ป้าย 350" กลายเป็นยอดรวม ฿2
   */
  assert.equal(extractGrandTotal('ทั้งหมด 2 ป้าย 350').total, null);
});

/* "ต่อชิ้น × จำนวน = ยอด" — จำนวนอยู่ในขั้นตอนสุดท้ายที่ร้านเขียน
 *
 * ป้ายเกษียณไม่ได้เขียนคำว่า "2 อัน" ไว้ที่ไหนเลย จำนวนอยู่ใน "900*2=1800"
 * อย่างเดียว ถ้าไม่อ่านก็ออกใบเสร็จเป็นชิ้นเดียว
 */
test('จำนวนอ่านได้จากขั้นตอนคิดเงินขั้นสุดท้าย', () => {
  const one = parseNaturalJob('ป้ายเกษียณ 1.2*1.7*600 = 900   900*2=1800');
  assert.equal(one.items[0].quantity, 2, 'ลูกค้าสั่งสอง แต่ออกใบเสร็จใบเดียว');
  assert.equal(one.items[0].unit_price, 900);
  assert.equal(one.items[0].total, 1800);

  // ราคาต่อชุดที่เขียนเป็นคำ ก็เอาจำนวนจากขั้นตอนสุดท้ายเหมือนกัน
  const set = parseNaturalJob('สแตนดี้ สูง 0.6*1.7  ชุดละ 1400   1400*2=2800');
  assert.equal(set.items[0].quantity, 2);
  assert.equal(set.items[0].unit_price, 1400);
});

/* ขนาดก็เขียนเป็น "เลข*เลข" เหมือนกัน — ห้ามอ่านเป็นจำนวน
 *
 * เส้นแบ่งคือผลคูณต้องเท่ากับยอดที่ร้านเขียนพอดี ถ้าไม่เท่าก็ไม่ใช่ขั้นตอน
 * คิดเงิน — ไม่งั้น "ป้าย 100*150 = 600" จะออกใบเสร็จเป็น 150 ชิ้น
 */
test('ขนาดไม่ถูกอ่านเป็นจำนวนชิ้น', () => {
  const sign = parseNaturalJob('ป้าย 100*150 = 600');
  assert.equal(sign.items[0].quantity, 1, 'ขนาดกลายเป็นจำนวนชิ้น');
  assert.equal(sign.items[0].total, 600);

  // ตัวคูณที่สี่แบบเดิมยังอ่านได้เหมือนเดิม (700 × 2 ≠ 2,100 จึงไม่ใช่ขั้นตอนสุดท้าย)
  const chain = parseNaturalJob('รูปครูยิ้ม 1*1.5*700*2=2,100');
  assert.equal(chain.items[0].quantity, 2);
  assert.equal(chain.items[0].total, 2100);
});

/* ยอดที่ร้านเขียนชนะ แต่ต้องเห็นว่ามันไม่ตรงกับสูตร
 *
 * 1.2 × 1.7 × 600 = 1,224 ไม่ใช่ 900 — ร้านเขียน 900 มาเอง (คราวก่อนร้านเขียน
 * บรรทัดเดียวกันนี้เป็น 2,448 คือ 1,224 × 2) ม่วงใช้เลขของร้าน แต่ต้องโชว์เลข
 * ที่คิดได้ไว้ข้าง ๆ ให้ร้านเห็นเองว่าต่างกัน ไม่ใช่กลืนไปเงียบ ๆ
 */
test('ยอดที่ไม่ตรงกับสูตร ต้องเห็นทั้งสองเลข', () => {
  const [job] = splitDump(WORKED).jobs;
  const sign = job.items[2];

  assert.equal(sign.total, 1800, 'ต้องใช้เลขที่ร้านเขียน');
  assert.match(String(sign.working), /2\.04 ตร\.ม\. × 600 = 1224/, 'เลขที่คิดได้หายไป');
  assert.match(String(sign.working), /ร้านคิด 1800$/);
});

test('กลุ่มยังแยกลูกค้าคนใหม่ได้เหมือนเดิม', () => {
  const groups = groupLines(`โฟมบอร์ด รร สบกอน
ป้ายเกษียณ 1.2*1.7*600 = 900   900*2=1800
ครูแดง ตรายาง 1 อัน 250`);

  assert.equal(groups.length, 2);
  assert.equal(groups[0].customer, 'รรสบกอน');
  assert.equal(groups[0].jobName, 'โฟมบอร์ด');
  assert.equal(groups[1].customer, null);
  assert.equal(groups[1].jobName, null, 'ชื่องานของหัวกลุ่มเก่าไหลข้ามลูกค้า');
});
