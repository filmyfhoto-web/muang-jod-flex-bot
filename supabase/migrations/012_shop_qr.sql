-- ม่วงจด — QR รับเงินของร้าน (shop_profiles.qr_path)
-- Safe to run repeatedly.
-- ============================================================
--
-- ร้านบอกว่า "ฉันเพิ่ม QR สแกนเงิน ไว้ในม่วงได้ไหม บางทีฉันหาในอัลบั้มไม่เจอ"
-- — เวลาลูกค้ายืนรออยู่หน้าร้านแล้วต้องไถหาในอัลบั้มรูป คือเวลาที่เสียไปจริง ๆ
-- ทุกครั้งที่เก็บเงิน
--
-- เก็บเป็น "ที่อยู่ของไฟล์" ในที่เก็บไฟล์ ไม่ใช่ลิงก์สำเร็จรูป เพราะลิงก์ที่
-- เซ็นไว้มีวันหมดอายุ ถ้าเก็บลิงก์ไว้ตรง ๆ อีกปีหนึ่ง QR จะหายไปเงียบ ๆ
-- ตอนนี้ตัวโปรแกรมเซ็นลิงก์ใหม่ทุกครั้งที่จะใช้

alter table public.shop_profiles
  add column if not exists qr_path text;

comment on column public.shop_profiles.qr_path is
  'ที่อยู่ไฟล์ QR รับเงินของร้านในที่เก็บไฟล์ (ไม่ใช่ URL) — ว่างได้';
