-- ============================================================
-- ม่วงจด — วันนัดรับงาน (due_date)
-- Safe to run repeatedly.
-- ============================================================
--
-- job_date คือวันที่ "จด" งานไว้ ส่วน due_date คือวันที่ "นัดรับ/ส่ง" งาน
-- คนละเรื่องกัน งานที่จดวันนี้อาจนัดรับอีกสิบวันข้างหน้าก็ได้ ปล่อยว่างได้
-- แปลว่าไม่ได้นัดวันไว้

alter table public.jobs add column if not exists due_date date;

-- "งานไหนต้องส่งก่อน" เป็นคำถามที่ถามบ่อยพอจะมี index — และถามภายในร้านเดียว
-- เสมอ เหมือนทุก query อื่นในระบบนี้
create index if not exists jobs_user_due_idx on public.jobs (user_id, due_date);
