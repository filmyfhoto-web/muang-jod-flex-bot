-- ม่วงจด — ลูกค้ามารับของหรือยัง (jobs.picked_up_at)
-- Safe to run repeatedly.
-- ============================================================
--
-- ร้านขอปุ่มสามปุ่มบนคิวงาน: ✅ รับแล้ว · 📛 ค้างจ่าย · ❎ ยังไม่มารับ
--
-- สามอย่างนี้เป็นสองเรื่องซ้อนกัน — "ของออกจากร้านไปหรือยัง" กับ "ได้เงิน
-- หรือยัง" ซึ่งของเดิมมีแต่เรื่องเงิน งานที่ทำเสร็จวางรออยู่หน้าร้าน กับงานที่
-- ลูกค้าหอบไปแล้วแต่ยังไม่จ่าย จึงหน้าตาเหมือนกันเป๊ะ ทั้งที่ต้องตามคนละแบบ
--
-- เก็บเป็นเวลาที่มารับ ไม่ใช่ true/false เพราะ "มารับเมื่อไหร่" เป็นคำถามที่
-- ร้านถามจริง ส่วน true/false ตอบได้แค่ว่ามารับแล้ว

alter table public.jobs
  add column if not exists picked_up_at timestamptz;

comment on column public.jobs.picked_up_at is
  'เวลาที่ลูกค้ามารับของ — ว่าง = ยังไม่มารับ';

-- คิวงานถามว่า "ของใครยังวางรออยู่" บ่อยพอที่จะมี index
create index if not exists jobs_user_pickup_idx
  on public.jobs (user_id, picked_up_at);
