-- เวลาที่เก็บเงินครบจริง — แยก "งานลงบัญชี (รอเก็บ)" ออกจาก "เก็บเงินแล้ว" ได้จริง
--
-- ของเดิมพอเก็บเงินงานที่ลงบัญชีไว้ ระบบจำได้แค่ว่า "จ่ายครบแล้ว" แต่ไม่รู้ว่า
-- เก็บได้วันไหน ใบลงบัญชีเลยเอารายรับไปขึ้นย้อนหลังที่วันลงบัญชี (booked_at)
-- แทนที่จะเป็นวันที่เงินเข้ามือจริง — ร้านเปิด "เงินวันนี้" แล้วไม่เห็นเงินที่เพิ่งตามเก็บมา
--
-- ว่าง = ยังเก็บไม่ครบ (หรือเป็นงานเก่าก่อนมีช่องนี้ ซึ่งใบลงบัญชีจะใช้วัน booked_at
-- แบบเดิม ไม่เดาวันให้)

alter table jobs add column if not exists paid_at timestamptz;

comment on column jobs.paid_at is
  'เวลาที่เก็บเงินครบ — ว่าง = ยังเก็บไม่ครบ (งานเก่าก่อนช่องนี้ก็ว่าง ใช้วันลงบัญชีแทน)';
