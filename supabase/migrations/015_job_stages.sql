-- ร้านเขียนสี่ขั้นนี้มาเอง:
--
--   งานส่วนไหน   เสร็จแล้ว *รับแล้ว
--                          *จ่ายแล้ว
--                          *ลงบัญชี
--                          *เงินสด
--
-- ของเดิมมีอยู่แล้วสองขั้นกลาง — picked_up_at (ลูกค้ามารับ) กับ balance_due
-- (ได้เงินหรือยัง) ขาดหัวกับท้าย: "ทำเสร็จในร้านแล้วหรือยัง" กับ "ลงบัญชี
-- ไปหรือยัง" สองอันนี้เป็นคนละคำถามกับสองอันกลางจริง ๆ
--
--   ทำเสร็จ    ของพร้อมแล้ว รออยู่หน้าร้าน — ต่างจาก "ยังทำไม่เสร็จ" ที่
--              โทรไปบอกลูกค้าให้มารับไม่ได้
--   ลงบัญชี    เงินก้อนนี้เข้าสมุดบัญชีแล้ว — ต่างจาก "ได้เงินแล้ว" ตรงที่
--              ได้เงินคือเรื่องของลูกค้า ลงบัญชีคือเรื่องของร้าน
--
-- เก็บเป็นเวลา ไม่ใช่ true/false เหมือน picked_up_at ด้วยเหตุผลเดียวกัน:
-- "เสร็จเมื่อไหร่" กับ "ลงบัญชีวันไหน" เป็นคำถามที่ร้านถามจริง

alter table public.jobs
  add column if not exists done_at   timestamptz,
  add column if not exists booked_at timestamptz;

comment on column public.jobs.done_at is
  'เวลาที่ทำงานเสร็จในร้าน — ว่าง = ยังทำไม่เสร็จ';
comment on column public.jobs.booked_at is
  'เวลาที่ลงบัญชีเงินก้อนนี้ — ว่าง = ยังไม่ได้ลง';

-- ------------------------------------------------------------
-- รับเงินมาด้วยอะไร
-- ------------------------------------------------------------
--
-- ใบลงบัญชีประจำวันต้องแยกเงินสดกับเงินโอน เพราะเงินสดอยู่ในลิ้นชัก ส่วนเงิน
-- โอนอยู่ในบัญชีธนาคาร คนทำบัญชีกระทบยอดคนละทาง
--
-- ว่าง = ยังไม่ได้บอก ซึ่งไม่เหมือน "เงินสด" — งานเก่าทุกใบที่จดไว้ก่อนหน้านี้
-- ไม่มีใครบอกไว้ เดาให้เป็นเงินสดก็เท่ากับแต่งตัวเลขให้คนทำบัญชี
alter table public.jobs
  add column if not exists pay_method text
    check (pay_method is null or pay_method in ('cash', 'transfer'));

comment on column public.jobs.pay_method is
  'รับเงินด้วยอะไร cash = เงินสด · transfer = โอน · ว่าง = ยังไม่ได้บอก';

-- ------------------------------------------------------------
-- ดัชนี
-- ------------------------------------------------------------
-- ตารางงานถามว่า "วันนี้มีอะไรค้างอยู่ขั้นไหน" ทุกครั้งที่เปิดหน้า
create index if not exists jobs_user_done_idx
  on public.jobs (user_id, done_at);

-- ใบลงบัญชีถามว่า "วันนี้ลงบัญชีอะไรไปแล้วบ้าง" วันละครั้ง แต่กวาดทั้งวัน
create index if not exists jobs_user_booked_idx
  on public.jobs (user_id, booked_at);

